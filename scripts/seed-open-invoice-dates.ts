export async function main() {
  if (!process.env.DATABASE_URL) {
    console.log('[seed-open-invoice-dates] geen DATABASE_URL — overslaan')
    return
  }
  const prisma = new PrismaClient()
  try {
    let updated = 0
    let skipped = 0
    for (const [invoiceNumber, dates] of Array.from(DATES.entries())) {
      const inv = await prisma.openInvoice.findUnique({
        where: { invoiceNumber },
        select: { id: true, issueDate: true, dueDate: true },
      })
      if (!inv) { skipped++; continue }
      const issueDate = new Date(dates.issueDate)
      const dueDate = new Date(dates.dueDate)
      // Idempotent: skip als datums al kloppen
      if (
        inv.issueDate && inv.dueDate &&
        inv.issueDate.toISOString().slice(0, 10) === dates.issueDate &&
        inv.dueDate.toISOString().slice(0, 10) === dates.dueDate
      ) {
        skipped++
        continue
      }
      await prisma.openInvoice.update({
        where: { id: inv.id },
        data: { issueDate, dueDate },
      })
      updated++
    }
    console.log(`[seed-open-invoice-dates] ${updated} bijgewerkt, ${skipped} al goed of niet gevonden`)
  } catch (err) {
    console.error('[seed-open-invoice-dates] mislukt (build gaat door):', err)
  } finally {
    await prisma.$disconnect().catch(() => {})
  }
}

